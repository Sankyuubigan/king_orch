/// Промпт для сигнального LLM-вызова: сохранить результат анализа как сигнал.
/// Правило «сначала вся история»: сигнал — инфраструктурный маркер, а не новый
/// анализ. Если по key значение уже установлено в истории сессии (прошлые
/// сигналы видны модели как сообщения вида {"key": значение}), повторная
/// эмиссия должна воспроизвести ЕГО, а не переанализировать текущий запрос —
/// иначе повторный прогон агента перезаписывает корректный сигнал (SSOT, core §2.1).
pub(crate) fn signal_request_prompt(contract_key: &str) -> String {
    format!(
        "Отлично. Теперь сохрани результат анализа как сигнал: вызови инструмент emit_signal с key=\"{}\" и value по контракту (точно той структуры, как описано в системном промпте). ПЕРЕД эмиссией проверь ВСЮ историю сессии (все сообщения, включая прошлые сигналы — они выглядят как JSON вида {{\"key\": значение}}): если по этому key значение уже установлено — сохрани ИМЕННО ЕГО, без повторного анализа; повторный анализ допустим только если значения ещё нет. Ответь ТОЛЬКО JSON с вызовом эмиссии — без пояснений.",
        contract_key
    )
}

/// Корректирующий хинт для ретрая сигнального вызова: модель должна вернуть
/// РОВНО один JSON-конверт emit_signal (без markdown и пояснений).
pub(crate) fn signal_retry_hint(contract_key: &str) -> String {
    format!(
        "⚠️ Твой ответ не был распознан как вызов emit_signal. Верни РОВНО ОДИН JSON без пояснений и без markdown: {{\"tool\": \"emit_signal\", \"arguments\": {{\"key\": \"{}\", \"value\": <значение по контракту из системного промпта>}}}}. Если в истории сессии уже есть сигнал с этим key — value должно быть ИМЕННО ЕГО значением, без повторного анализа.",
        contract_key
    )
}

