/**
 * SSOT-форматтер длительности для UI чата (PRP 07.11.26 «Время ответа —
 * минуты и секунды»): секунды с десятой доли до минуты, дальше — минуты и
 * секунды без десятых.
 *
 * Контракт:
 * - sec < 60 → «45.3 сек» (десятые доли);
 * - sec ≥ 60 → «3 мин 05 сек» (минуты без ведущего нуля, секунды — всегда
 *   две цифры, без десятых);
 * - границу решает ОКРУГЛЁННОЕ значение: 59.96 → «1 мин 00 сек» (а не
 *   «60.0 сек» и не «0 мин 60 сек»).
 *
 * Единственный источник правды: все точки чата (время сообщения, ⏱-мета
 * мыслей, отчёты сабагентов) вызывают formatDuration; локальные копии
 * `toFixed(1)` запрещены.
 */
export function formatDuration(sec: number): string {
  const total = Math.round(sec);
  if (total >= 60) {
    const min = Math.floor(total / 60);
    const rest = total % 60;
    return `${min} мин ${String(rest).padStart(2, "0")} сек`;
  }
  return `${sec.toFixed(1)} сек`;
}
